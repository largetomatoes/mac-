import assert from 'node:assert/strict';
import {load,plain} from './load-ts.cjs';
const model=load('lib/notebook.ts'),cards=load('lib/card-collection.ts');
let data=model.normalize(model.changeCoreQuestion(plain(model.initialNotebook),'虚构核心问题'));
data={...data,cards:[{id:'card',text:'完整原话',origin:'自己的思考',source:'来源',at:'2026-10-01T00:00:00Z',thoughts:[{id:'later',text:'后续理解',at:'2026-10-02T00:00:00Z'}]}],links:[{id:'link',from:'card',to:'world',type:'相关'}]};
assert.equal(cards.cardKind(data.cards[0]),'idea');
data=cards.setCardKind(data,'card','question');
const a=cards.placeCardQuestion(data,'card','world','第一个问题'),b=cards.placeCardQuestion(a.data,'card','world','另一个独立问题');
assert.notEqual(a.questionId,b.questionId);
assert.equal(cards.cardQuestions(b.data.cards[0],b.data).length,2);
assert.equal(b.data.cards[0].thoughts.length,1);assert.equal(b.data.links[0].from,'card');
assert.equal(b.data.notes.find(n=>n.id===a.questionId).body,'完整原话');
const changed=cards.editCard(b.data,'card',{text:'后来改写',origin:'自己的思考',source:'来源',kind:'question',tags:['语言','语言','关系']});
assert.equal(changed.cards[0].revisions.at(-1).text,'完整原话');
assert.deepEqual(plain(changed.cards[0].tags),['语言','关系']);
assert.equal(changed.notes.find(n=>n.id===a.questionId).body,'完整原话');
assert.equal(changed.cards[0].adoptions[0].text,'完整原话');
assert.throws(()=>cards.placeCardQuestion(data,'card','missing','问题'));assert.throws(()=>cards.placeCardQuestion(data,'card','world',''));
console.log('PASS independent card edits, explicit multiple question adoptions, retained original thoughts/links and source snapshots');
